package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"koschei/api/internal/radaradapter/builtin"
	"os"
	"strings"
)

func main() {
	path := flag.String("output", "../../docs/CHAIN_CAPABILITY_MATRIX.md", "matrix output")
	check := flag.Bool("check", false, "fail on drift")
	jsonMode := flag.Bool("json", false, "print catalog and measured fixture calls")
	flag.Parse()
	catalog := builtin.Catalog()
	counts := builtin.FixtureRequestCounts()
	if *jsonMode {
		json.NewEncoder(os.Stdout).Encode(map[string]any{"catalog": catalog, "fixture_requests": counts})
		return
	}
	var out bytes.Buffer
	out.WriteString("# Chain capability matrix\n\nGenerated by `go run ./cmd/radar-capability-gen`; do not edit by hand.\n\nExecutable = synthetic offline fixture conformance, not deployed/healthy/complete. All new adapters are observe-first and cannot grade. Existing Solana and compatibility probes keep their separate routes. Provider URLs/keys must be configured at runtime; no live provider validation was performed by this generator.\n\n| Network | Status | Executable target classes | Sources | Archive / scope limitation | Fixture | Measured fixture requests |\n|---|---|---|---|---|---|---|\n")
	for _, c := range catalog {
		fmt.Fprintf(&out, "| %s | %s | %s | %s | %s | %s | %d |\n", c.Network, c.Status, strings.Join(c.TargetClasses, ", "), strings.Join(c.Sources, "; "), strings.Join(c.ArchivalRequirements, "; "), c.Fixture, counts[c.Network])
	}
	out.WriteString("\nA missing class is not supported by this registry. Partial investigation limitations are returned with every collection; see MASTER-PROMPT-STATUS.md for requirements that remain unfinished. Fixture call counts are bounded smoke scenarios, not a full deep-investigation bill.\n")
	if *check {
		old, e := os.ReadFile(*path)
		if e != nil || !bytes.Equal(old, out.Bytes()) {
			fmt.Fprintln(os.Stderr, "capability matrix drift; regenerate")
			os.Exit(1)
		}
		return
	}
	if e := os.WriteFile(*path, out.Bytes(), 0644); e != nil {
		panic(e)
	}
}
